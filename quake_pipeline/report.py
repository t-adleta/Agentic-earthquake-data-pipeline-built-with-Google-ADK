def _table(rows: list[dict], columns: list[tuple[str, str]]) -> str:
    """columns = [(key, header)]. Numbers are right-aligned."""
    if not rows:
        return "<p>No data.</p>"
    is_num = lambda x: isinstance(x, (int, float)) and not isinstance(x, bool)
    head = "".join(f'<th class="{"num" if is_num(rows[0].get(k)) else ""}">{html.escape(h)}</th>'
                   for k, h in columns)
    body = ""
    for r in rows:
        body += "<tr>" + "".join(
            f'<td class="{"num" if is_num(r.get(k)) else ""}">{html.escape(str(r.get(k, "")))}</td>'
            for k, _ in columns) + "</tr>"
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def build_html(summary: dict, insights: str) -> str:
    k = summary["kpis"]
    kpis = [
        (f"{k.get('total_events', 0):,}", "earthquakes"),
        (k.get("max_magnitude", "-"), "strongest magnitude"),
        (k.get("avg_magnitude", "-"), "average magnitude"),
        (k.get("events_m5_plus", 0), "magnitude 5 or higher"),
        (k.get("regions_affected", 0), "regions affected"),
        (k.get("tsunami_flagged", 0), "tsunami-flagged events"),
    ]
    kpi_html = "".join(f'<div class="kpi"><b>{html.escape(str(v))}</b><span>{html.escape(l)}</span></div>'
                       for v, l in kpis)
    subtitle = (f"{k.get('date_range', 'No events')} &middot; magnitude "
                f"{summary.get('min_magnitude', 0)} and above &middot; feed period: "
                f"past {html.escape(str(summary.get('period', '')))}")
    quality_rows = [{"check": key.replace("_", " "), "rows": val}
                    for key, val in summary.get("data_quality", {}).items()]
    chart_data = {"daily": summary["daily"], "by_magnitude_class": summary["by_magnitude_class"]}

    replacements = {
        "__SUBTITLE__": subtitle,
        "__KPIS__": kpi_html,
        "__INSIGHTS__": html.escape(insights or "No insights were provided."),
        "__REGIONS__": _table(summary["top_regions"], [
            ("region", "Region"), ("events", "Earthquakes"), ("avg_magnitude", "Avg magnitude"),
            ("max_magnitude", "Max magnitude"), ("avg_depth_km", "Avg depth (km)")]),
        "__STRONGEST__": _table(summary["strongest_events"], [
            ("time_utc", "Time"), ("magnitude", "Magnitude"), ("place", "Location"),
            ("depth_km", "Depth (km)")]),
        "__QUALITY__": _table(quality_rows, [("check", "Check"), ("rows", "Rows")]),
        "__RUN_ID__": html.escape(str(summary.get("run_id", ""))),
        "__DATA__": json.dumps(chart_data).replace("</", "<\\/"),
    }
    page = TEMPLATE
    for token, value in replacements.items():
        page = page.replace(token, value)
    return page
